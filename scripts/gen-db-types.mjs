#!/usr/bin/env node
// Generates src/data/database.types.ts from the migrated schema, in the same
// shape as `supabase gen types typescript`, so @supabase/supabase-js gets
// fully typed queries. Runs against the throwaway database built by
// supabase/tests/reset-local-db.sh (no Docker or Supabase account needed).
//
//   npm run db:types          regenerate
//   npm run db:types:check    fail if the committed file is stale (CI)
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import pg from 'pg'

const root = fileURLToPath(new URL('..', import.meta.url))
const outFile = `${root}src/data/database.types.ts`
const check = process.argv.includes('--check')

const url = execFileSync('bash', [`${root}supabase/tests/reset-local-db.sh`], { encoding: 'utf8' })
  .trim().split('\n').pop()
const client = new pg.Client({ connectionString: url })
await client.connect()

const q = async (sql) => (await client.query(sql)).rows

const enums = await q(`
  select t.typname as name, array_agg(e.enumlabel::text order by e.enumsortorder) as labels
  from pg_type t join pg_enum e on e.enumtypid = t.oid join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' group by t.typname order by t.typname`)
const enumNames = new Set(enums.map((e) => e.name))

const columns = await q(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable,
         c.column_default is not null as has_default, c.is_identity = 'YES' as identity,
         c.identity_generation, c.ordinal_position
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`)

const fks = await q(`
  select con.conname, cl.relname as table_name, rcl.relname as ref_table,
    (select array_agg(a.attname::text order by k.ord) from unnest(con.conkey) with ordinality k(attnum, ord)
       join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum) as columns,
    (select array_agg(a.attname::text order by k.ord) from unnest(con.confkey) with ordinality k(attnum, ord)
       join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum) as ref_columns,
    exists (select 1 from pg_constraint u where u.conrelid = con.conrelid and u.contype in ('p', 'u')
            and (select array_agg(x order by x) from unnest(u.conkey) x) = (select array_agg(x order by x) from unnest(con.conkey) x)) as one_to_one,
    rn.nspname as ref_schema
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
  join pg_class rcl on rcl.oid = con.confrelid join pg_namespace rn on rn.oid = rcl.relnamespace
  where con.contype = 'f' and n.nspname = 'public'
  order by cl.relname, con.conname`)

const functions = await q(`
  select p.proname as name, p.proretset as retset, p.pronargdefaults as ndefaults,
         pg_get_function_result(p.oid) as result,
         rt.typname as ret_type, rt.typtype as ret_typtype, rt.typrelid <> 0 as ret_is_table,
         coalesce(p.proargnames, '{}') as argnames, coalesce(p.proargmodes::text[], '{}') as argmodes,
         (select array_agg(t.typname::text order by o) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality u(oid, o)
            join pg_type t on t.oid = u.oid) as argtypes
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace join pg_type rt on rt.oid = p.prorettype
  where n.nspname = 'public' and rt.typname <> 'trigger' and p.prokind = 'f'
  order by p.proname`)

await client.end()

function tsType(udt) {
  if (udt.startsWith('_')) return `${tsType(udt.slice(1))}[]`
  if (enumNames.has(udt)) return `Database["public"]["Enums"]["${udt}"]`
  switch (udt) {
    case 'int2': case 'int4': case 'int8': case 'float4': case 'float8': case 'numeric': return 'number'
    case 'bool': return 'boolean'
    case 'json': case 'jsonb': return 'Json'
    case 'void': return 'undefined'
    default: return 'string'
  }
}

const tables = new Map()
for (const c of columns) {
  if (!tables.has(c.table_name)) tables.set(c.table_name, [])
  tables.get(c.table_name).push(c)
}

const ind = (n) => '  '.repeat(n)
let out = `// GENERATED by scripts/gen-db-types.mjs from supabase/migrations. Do not edit.
// Regenerate with \`npm run db:types\`.

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[]

export type Database = {
  public: {
    Tables: {
`
for (const [name, cols] of tables) {
  out += `${ind(3)}${name}: {\n${ind(4)}Row: {\n`
  for (const c of cols) out += `${ind(5)}${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}\n`
  out += `${ind(4)}}\n${ind(4)}Insert: {\n`
  for (const c of cols) {
    if (c.identity && c.identity_generation === 'ALWAYS') { out += `${ind(5)}${c.column_name}?: never\n`; continue }
    const opt = c.nullable || c.has_default || c.identity
    out += `${ind(5)}${c.column_name}${opt ? '?' : ''}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}\n`
  }
  out += `${ind(4)}}\n${ind(4)}Update: {\n`
  for (const c of cols) {
    if (c.identity && c.identity_generation === 'ALWAYS') { out += `${ind(5)}${c.column_name}?: never\n`; continue }
    out += `${ind(5)}${c.column_name}?: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''}\n`
  }
  out += `${ind(4)}}\n${ind(4)}Relationships: [\n`
  for (const fk of fks.filter((f) => f.table_name === name && f.ref_schema === 'public')) {
    out += `${ind(5)}{\n${ind(6)}foreignKeyName: "${fk.conname}"\n${ind(6)}columns: [${fk.columns.map((x) => `"${x}"`).join(', ')}]\n` +
      `${ind(6)}isOneToOne: ${fk.one_to_one}\n${ind(6)}referencedRelation: "${fk.ref_table}"\n` +
      `${ind(6)}referencedColumns: [${fk.ref_columns.map((x) => `"${x}"`).join(', ')}]\n${ind(5)}},\n`
  }
  out += `${ind(4)}]\n${ind(3)}}\n`
}
out += `${ind(2)}}\n${ind(2)}Views: {\n${ind(3)}[_ in never]: never\n${ind(2)}}\n${ind(2)}Functions: {\n`

for (const f of functions) {
  const modes = f.argmodes.length ? f.argmodes : f.argtypes?.map(() => 'i') ?? []
  const args = []
  const outs = []
  ;(f.argtypes ?? []).forEach((t, i) => {
    const entry = { name: f.argnames[i], type: t }
    if (modes[i] === 'o' || modes[i] === 't') outs.push(entry)
    else args.push(entry)
  })
  out += `${ind(3)}${f.name}: {\n${ind(4)}Args: `
  if (args.length === 0) out += `never\n`
  else {
    out += `{\n`
    args.forEach((a, i) => {
      const optional = i >= args.length - f.ndefaults
      out += `${ind(5)}${a.name}${optional ? '?' : ''}: ${tsType(a.type)}\n`
    })
    out += `${ind(4)}}\n`
  }
  let ret
  if (outs.length) {
    ret = `{\n${outs.map((o) => `${ind(5)}${o.name}: ${tsType(o.type)}`).join('\n')}\n${ind(4)}}${f.retset ? '[]' : ''}`
  } else if (f.ret_is_table && tables.has(f.ret_type)) {
    ret = `Database["public"]["Tables"]["${f.ret_type}"]["Row"]${f.retset ? '[]' : ''}`
  } else {
    ret = `${tsType(f.ret_type)}${f.retset ? '[]' : ''}`
  }
  out += `${ind(4)}Returns: ${ret}\n${ind(3)}}\n`
}
out += `${ind(2)}}\n${ind(2)}Enums: {\n`
for (const e of enums) out += `${ind(3)}${e.name}:\n${e.labels.map((l) => `${ind(4)}| "${l}"`).join('\n')}\n`
out += `${ind(2)}}\n${ind(2)}CompositeTypes: {\n${ind(3)}[_ in never]: never\n${ind(2)}}\n${ind(1)}}\n}

type PublicSchema = Database["public"]

export type Tables<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Row"]
export type TablesInsert<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Insert"]
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> = PublicSchema["Tables"][T]["Update"]
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T]
`

if (check) {
  const current = readFileSync(outFile, 'utf8')
  if (current !== out) {
    console.error('src/data/database.types.ts is out of date. Run `npm run db:types` and commit the result.')
    process.exit(1)
  }
  console.log('database.types.ts is up to date')
} else {
  writeFileSync(outFile, out)
  console.log(`wrote ${outFile}`)
}
